// Read the committed photography tiers and write:
//   src/data/photo-dimensions.json   actual pixel sizes (srcset truth)
//   src/styles/photo-frames.css      per-photo plate frames (aspect + caps)
//
// Width descriptors on the site must match these pixels. The ingest tiers
// are fit-inside a square (400 / 1200 / 2400 on the long edge), so a portrait
// file is narrower than the tier label. Advertising the label as the `w`
// descriptor makes the browser pick a file that is too small and then scale it.
import sharp from 'sharp';
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const base = join(root, 'public/images/photography');
const tiers = ['thumb', 'gallery', 'hero', 'portrait'];

/** @type {Record<string, Record<string, {w: number, h: number}>>} */
const table = {};

for (const tier of tiers) {
  const dir = join(base, tier);
  let names = [];
  try {
    names = readdirSync(dir);
  } catch {
    continue;
  }
  for (const name of names) {
    if (!name.endsWith('.webp')) continue;
    const stem = name.slice(0, -5);
    const meta = await sharp(join(dir, name)).metadata();
    if (!meta.width || !meta.height) {
      throw new Error(`no size for ${tier}/${name}`);
    }
    table[stem] ??= {};
    table[stem][tier] = { w: meta.width, h: meta.height };
  }
}

const stems = Object.keys(table).sort();
const ordered = {};
for (const stem of stems) ordered[stem] = table[stem];

writeFileSync(
  join(root, 'src/data/photo-dimensions.json'),
  JSON.stringify(ordered, null, 2) + '\n',
);

const frames = [];
frames.push('/* Generated by scripts/emit-photo-dimensions.mjs.');
frames.push('   Plate frames: own aspect, never wider than the bitmap,');
frames.push('   never taller than 80svh. Do not hand-edit. */');
for (const stem of stems) {
  const hero = table[stem].hero;
  if (!hero) continue;
  const cls = 'pf-' + stem.replace(/[^a-z0-9-]/gi, '');
  frames.push(
    `.${cls}{width:100%;max-width:min(100%,${hero.w}px,calc(80svh * ${hero.w} / ${hero.h}));aspect-ratio:${hero.w} / ${hero.h};}`,
  );
}
frames.push('');
writeFileSync(join(root, 'src/styles/photo-frames.css'), frames.join('\n'));

console.log(`[dimensions] ${stems.length} photographs`);
